"""Guidelines for external agents that enrich the graph (RF-20).

The guide ships with the package, so any agent can read it with `kg guide`
(like the schema with `kg schema`), and `kg guide --skill` exports it as an
agent skill. `.agents/skills/kg-graph/SKILL.md` in this repo is that export.
"""

from __future__ import annotations

import json
from importlib import resources
from pathlib import Path

SKILL_NAME = "kg-graph"
SKILL_DESCRIPTION = (
    "Enrich a kg knowledge graph with what a parser cannot see: documents, "
    "design decisions, domain concepts, services and endpoints. Use it after "
    "`kg extract`, when asked to map, document or explain a repo with kg, or "
    "before answering questions from its graph."
)


def guide_path() -> Path:
    """Path of the installed guide."""
    return Path(str(resources.files("kg.agents").joinpath("guide.md")))


def load_guide() -> str:
    """The guide, in Markdown."""
    return resources.files("kg.agents").joinpath("guide.md").read_text("utf-8")


def skill_text() -> str:
    """The guide as a skill: YAML front matter plus the guide.

    The description is a JSON string, which is also a valid YAML scalar.
    """
    description = json.dumps(SKILL_DESCRIPTION)
    return (
        f"---\nname: {SKILL_NAME}\ndescription: {description}\n---\n\n"
        f"<!-- Generated by `kg guide --skill`; edit src/kg/agents/guide.md. -->\n\n"
        f"{load_guide()}"
    )
